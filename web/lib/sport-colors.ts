// Цвета видов спорта. Без server-only: нужны и серверу (getSportTypes),
// и клиентскому графику тренировок.

// Первые 12 — подобранные вручную, хорошо различимы на тёмном и светлом фоне.
export const SPORT_PALETTE = [
  "#e8a23a",  // янтарный   — сила, зал
  "#4a8fe8",  // синий      — команда, волейбол
  "#8f5ec8",  // фиолетовый — групповые, скалодром
  "#d05a30",  // оранж-кр   — бег, HIIT
  "#4fa85a",  // зелёный    — ходьба, природа
  "#2aa09a",  // бирюзовый  — бассейн, функциональная
  "#d4a030",  // золотой    — сноуборд, скайдайв
  "#c85e88",  // розовый    — пилатес, танцы
  "#6b7fd7",  // барвинок
  "#3ab0d8",  // голубой
  "#9aa83a",  // оливковый
  "#b07a4a",  // коричневый
];

// Цвет по порядковому номеру вида спорта: уникален для каждого номера.
// После палитры — оттенки по «золотому углу», минуя красный: им на графиках
// обозначена мигрень.
export function sportColor(i: number): string {
  if (i < SPORT_PALETTE.length) return SPORT_PALETTE[i];
  let hue = (95 + (i - SPORT_PALETTE.length) * 137.508) % 360;
  if (hue < 40 || hue > 330) hue = (hue + 70) % 360;
  return `oklch(0.66 0.13 ${hue.toFixed(0)})`;
}
